var (
	positiveIntegerPattern = regexp.MustCompile(`^(.+?) 必须是(?:有效的)?正整数$`)
	nonNegativePattern     = regexp.MustCompile(`^(.+?) 必须是(?:大于等于 0 的|非负)整数$`)
	rangePattern           = regexp.MustCompile(`^(.+?) 必须(?:是|在) ([0-9]+) 到 ([0-9]+) 之间(?:的整数)?$`)
	maxLengthPattern       = regexp.MustCompile(`^(.+?) 最长为 ([0-9]+) 个字符$`)
	retryAfterPattern      = regexp.MustCompile(`^请在 ([0-9]+) 秒后重试。?$`)
	confirmationPattern    = regexp.MustCompile(`^确认文本必须为 (.+)$`)
	ruleExpiryPattern      = regexp.MustCompile(`^第 ([0-9]+) 条规则的过期时间格式错误$`)
)

// LocalizeText translates API response text that predates message keys.
// It intentionally targets response messages only; persisted task, audit, and
// runtime logs keep their original text for historical consistency.
func LocalizeText(locale, text string) string {
	if Canonical(locale) != LocaleEnUS || strings.TrimSpace(text) == "" {
		return text
	}
	if translated, ok := englishErrorTexts[text]; ok {
		return translated
	}
	if translated, ok := translateValidationText(text); ok {
		return translated
	}
	if translated, ok := translateDynamicErrorText(text); ok {
		return translated
	}
	if translated, ok := translateStructuredErrorText(text); ok {
		return translated
	}
	return text
}

func translateDynamicErrorText(text string) (string, bool) {
	if matches := confirmationPattern.FindStringSubmatch(text); len(matches) == 2 {
		return fmt.Sprintf("The confirmation text must be %s", matches[1]), true
	}
	if matches := ruleExpiryPattern.FindStringSubmatch(text); len(matches) == 2 {
		return fmt.Sprintf("Rule %s has an invalid expiration-time format", matches[1]), true
	}
	prefixes := []struct {
		zh string
		en string
	}{
		{"计划任务服务未初始化，无法执行当前操作；具体原因：", "The scheduled-task service is not initialized, so the operation cannot be performed."},
		{"令牌校验失败：", "Token validation failed."},
		{"当前接口要求权限：", "The endpoint requires permission: "},
		{"读取当前用户权限失败：", "Failed to load the current user permissions."},
		{"未找到与当前 HTTP 方法和路径匹配的接口路由：", "No API route matches the current HTTP method and path."},
	}
	for _, prefix := range prefixes {
		if !strings.HasPrefix(text, prefix.zh) {
			continue
		}
		if prefix.zh == "当前接口要求权限：" {
			return prefix.en + strings.TrimSpace(strings.TrimPrefix(text, prefix.zh)), true
		}
		return prefix.en, true
	}
	return "", false
}

func ContainsHan(text string) bool {
	for _, value := range text {
		if unicode.Is(unicode.Han, value) {
			return true
		}
	}
	return false
}

func translateValidationText(text string) (string, bool) {
	if matches := positiveIntegerPattern.FindStringSubmatch(text); len(matches) == 2 {
		return fmt.Sprintf("%s must be a positive integer", parameterName(matches[1])), true
	}
	if matches := nonNegativePattern.FindStringSubmatch(text); len(matches) == 2 {
		return fmt.Sprintf("%s must be a non-negative integer", parameterName(matches[1])), true
	}
	if matches := rangePattern.FindStringSubmatch(text); len(matches) == 4 {
		return fmt.Sprintf("%s must be between %s and %s", parameterName(matches[1]), matches[2], matches[3]), true
	}
	if matches := maxLengthPattern.FindStringSubmatch(text); len(matches) == 3 {
		return fmt.Sprintf("%s must not exceed %s characters", parameterName(matches[1]), matches[2]), true
	}
	if matches := retryAfterPattern.FindStringSubmatch(text); len(matches) == 2 {
		return fmt.Sprintf("Retry after %s seconds.", matches[1]), true
	}
	return "", false
}

func parameterName(value string) string {
	value = strings.TrimSpace(value)
	if translated, ok := englishTerms[value]; ok {
		return translated
	}
	return value
}

func translateStructuredErrorText(text string) (string, bool) {
	patterns := []struct {
		suffix string
		format string
	}{
		{"参数格式不正确", "The %s parameters have an invalid format"},
		{"参数格式错误", "The %s parameters have an invalid format"},
		{"参数无效", "The %s parameters are invalid"},
		{"不存在", "%s does not exist"},
		{"不可用，请稍后重试", "%s is unavailable. Please try again later"},
		{"不可用", "%s is unavailable"},
		{"无效", "%s is invalid"},
		{"不能为空", "%s must not be empty"},
		{"不完整", "%s is incomplete"},
		{"超时", "%s timed out"},
	}
	for _, pattern := range patterns {
		if !strings.HasSuffix(text, pattern.suffix) {
			continue
		}
		subject := strings.TrimSpace(strings.TrimSuffix(text, pattern.suffix))
		if translated, ok := englishTerms[subject]; ok {
			return fmt.Sprintf(pattern.format, translated), true
		}
	}

	if strings.HasSuffix(text, "失败") {
		body := strings.TrimSpace(strings.TrimSuffix(text, "失败"))
		for _, action := range englishActions {
			if !strings.HasPrefix(body, action.zh) {
				continue
			}
			resource := strings.TrimSpace(strings.TrimPrefix(body, action.zh))
			if translated, ok := englishTerms[resource]; ok {
				return fmt.Sprintf("Failed to %s %s", action.en, translated), true
			}
		}
	}
	return "", false
}

